import csv
import hashlib
import importlib.util
from importlib.machinery import SourceFileLoader
import json
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path
from typing import Any

from materializer_sql import normalize_sql_layout
import logos_legacy_wetune


ROOT = Path(__file__).resolve().parents[3]
WORKFLOW_ROOT = ROOT.parent
EXPORTER_PATH = ROOT / "scripts/export-benchmark-ir"
DEFAULT_CONFIG = "benchmarks/core/ingestion.json"
DEFAULT_OUTPUT = "benchmarks/core/.generated/logos"
RBOT_ROOT = ROOT / "benchmarks/core/rbot"
RBOT_MANIFEST = RBOT_ROOT / "rewrite-pairs.manifest.json"
FROZEN_RBOT_MANIFEST_SHA256 = (
    "443fecfdd35d13e1997b15eaaa48e294733082a40d4652973bed767dce9cf66b"
)
FROZEN_RBOT_SCHEMA_SHA256 = {
    "dsb": "805a1b08edf45fee0326efca6056ca881d92a00969e102fe731cf0781d24c0ea",
    "tpch": "4fc33b97f09b573d748179f6a0a4d049f8d5057c7919ce2c163bb80e1af23eef",
}
CALCITE_AUTHORITY_ROOT = ROOT / "benchmarks/core/.generated/calcite-ir"
NON_RBOT_BASELINE = (
    WORKFLOW_ROOT
    / "var/codex-background/logos-rbot-provenance-r1.non-rbot-baseline.json"
)
SQLGLOT_BOOTSTRAP = ROOT / "benchmarks/scripts/sqlglot-normalize"
WETUNE_ID = "wetune-issues"
RBOT_IDS = frozenset(("rbot-dsb", "rbot-tpch"))
SOURCE_NODE_ID = re.compile(r"^(\d+):(\d+)-(\d+):(\d+)$")


class LogosMaterializationError(ValueError):
    """A source or frozen materialization contract failed closed."""


def main() -> int:
    parser = argparse.ArgumentParser(
        description=(
            "Materialize the independent Logos SQL/integrity/Calcite-authority "
            "profile without consulting an external solver frontend."
        )
    )
    parser.add_argument("--config", default=DEFAULT_CONFIG)
    parser.add_argument("--output-dir", default=DEFAULT_OUTPUT)
    parser.add_argument(
        "--target",
        choices=("all", "wetune", "nonwetune"),
        default="all",
    )
    parser.add_argument("--benchmark", action="append")
    parser.add_argument(
        "--case", action="append", help="Case-id regex. May be repeated."
    )
    parser.add_argument("--limit", type=int)
    parser.add_argument("--force", action="store_true")
    parser.add_argument(
        "--verify-non-rbot-baseline",
        action="store_true",
        help=(
            "After materialization, compare every non-R-Bot generated byte with "
            "the supervisor-owned 1,320-file campaign baseline."
        ),
    )
    args = parser.parse_args()

    if args.limit is not None and args.limit < 1:
        parser.error("--limit must be at least 1")

    config = json.loads(resolve_path(args.config).read_text(encoding="utf-8"))
    output_dir = resolve_path(args.output_dir)
    selected = set(args.benchmark or ())
    case_patterns = [re.compile(pattern) for pattern in args.case or ()]

    exporter = load_exporter()
    manifest, manifest_cases = load_rbot_manifest()
    if rbot_materialization_requested(args.target, selected):
        validate_rbot_schema_authority()
        validate_rbot_exported_case_set(config, exporter, manifest_cases)
    maybe_clear_owned_outputs(output_dir, args)
    materialized = 0
    failed = 0

    if args.target in {"all", "wetune"} and (not selected or WETUNE_ID in selected):
        count, errors = materialize_wetune_cases(
            config=config,
            output_dir=output_dir / "wetune-issues",
            case_patterns=case_patterns,
            limit=remaining_limit(args.limit, materialized),
        )
        materialized += count
        failed += errors

    if args.target in {"all", "nonwetune"} and not limit_reached(
        args.limit, materialized
    ):
        for benchmark in config["benchmarks"]:
            benchmark_id = benchmark["id"]
            if benchmark_id == WETUNE_ID:
                continue
            if selected and benchmark_id not in selected:
                continue
            for case in exporter.iter_cases(config, benchmark):
                if case_patterns and not any(
                    pattern.search(case.case_id) for pattern in case_patterns
                ):
                    continue
                if limit_reached(args.limit, materialized):
                    break
                try:
                    if benchmark_id in RBOT_IDS:
                        materialize_rbot_case(
                            config,
                            case,
                            output_dir / "nonwetune-flat",
                            manifest,
                            manifest_cases,
                        )
                    else:
                        materialize_legacy_non_rbot_case(
                            config,
                            case,
                            output_dir / "nonwetune-flat",
                            exporter,
                        )
                    materialized += 1
                    print(
                        f"materialized {benchmark_id}/{case.case_id}",
                        file=sys.stderr,
                    )
                except Exception as exc:
                    failed += 1
                    print(
                        f"failed {benchmark_id}/{case.case_id}: {exc}",
                        file=sys.stderr,
                    )

    if args.verify_non_rbot_baseline:
        verify_non_rbot_baseline(output_dir, NON_RBOT_BASELINE)
        print("verified non-R-Bot baseline: files=1320 changed=0", file=sys.stderr)

    print(
        f"summary: materialized={materialized} failed={failed}",
        file=sys.stderr,
    )
    return 1 if failed else 0


def remaining_limit(limit: int | None, materialized: int) -> int | None:
    return None if limit is None else max(0, limit - materialized)


def limit_reached(limit: int | None, materialized: int) -> bool:
    return limit is not None and materialized >= limit


def maybe_clear_owned_outputs(output_dir: Path, args: argparse.Namespace) -> None:
    filtered = bool(args.benchmark or args.case or args.limit is not None)
    if not args.force or filtered:
        output_dir.mkdir(parents=True, exist_ok=True)
        return
    owned = []
    if args.target in {"all", "wetune"}:
        owned.append(output_dir / "wetune-issues")
    if args.target in {"all", "nonwetune"}:
        owned.append(output_dir / "nonwetune-flat")
    for path in owned:
        if path.exists():
            shutil.rmtree(path)
    output_dir.mkdir(parents=True, exist_ok=True)


def load_exporter():
    loader = SourceFileLoader("logos_materialization_case_source", str(EXPORTER_PATH))
    spec = importlib.util.spec_from_loader(loader.name, loader)
    if spec is None or spec.loader is None:
        raise LogosMaterializationError(f"cannot load case source from {EXPORTER_PATH}")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def resolve_path(path: str | Path) -> Path:
    candidate = Path(path)
    return candidate if candidate.is_absolute() else ROOT / candidate


def sha256_bytes(value: bytes) -> str:
    return hashlib.sha256(value).hexdigest()


def load_rbot_manifest(
    path: Path = RBOT_MANIFEST,
) -> tuple[dict[str, Any], dict[str, dict[str, Any]]]:
    value = path.read_bytes()
    actual_digest = sha256_bytes(value)
    if actual_digest != FROZEN_RBOT_MANIFEST_SHA256:
        raise LogosMaterializationError(
            "R-Bot manifest digest changed from the frozen campaign launch: "
            f"expected {FROZEN_RBOT_MANIFEST_SHA256}, got {actual_digest}"
        )
    document = json.loads(value)
    rows = document.get("cases")
    if not isinstance(rows, list) or len(rows) != 59:
        raise LogosMaterializationError("R-Bot manifest must contain exactly 59 cases")
    by_case: dict[str, dict[str, Any]] = {}
    for row in rows:
        if not isinstance(row, dict) or not isinstance(row.get("case"), str):
            raise LogosMaterializationError("R-Bot manifest contains a malformed case")
        case_id = row["case"]
        if case_id in by_case:
            raise LogosMaterializationError(f"duplicate R-Bot case {case_id}")
        by_case[case_id] = row
    return document, by_case


def rbot_materialization_requested(target: str, selected: set[str]) -> bool:
    return target in {"all", "nonwetune"} and (
        not selected or bool(selected & RBOT_IDS)
    )


def validate_rbot_schema_authority() -> None:
    for workload in sorted(FROZEN_RBOT_SCHEMA_SHA256):
        bound_rbot_schema_bytes(workload)


def validate_rbot_exported_case_set(
    config: dict[str, Any],
    exporter: Any,
    manifest_cases: dict[str, dict[str, Any]],
) -> None:
    """Bind every filtered developer run to the complete frozen R-Bot superset."""

    benchmark_rows = [
        benchmark
        for benchmark in config.get("benchmarks", [])
        if isinstance(benchmark, dict) and benchmark.get("id") in RBOT_IDS
    ]
    benchmarks = {benchmark["id"]: benchmark for benchmark in benchmark_rows}
    if len(benchmark_rows) != len(RBOT_IDS) or set(benchmarks) != set(RBOT_IDS):
        raise LogosMaterializationError(
            "configured R-Bot workloads differ from the frozen authority: "
            f"expected={sorted(RBOT_IDS)} "
            f"actual={[benchmark['id'] for benchmark in benchmark_rows]}"
        )

    exported: list[str] = []
    for benchmark_id in sorted(RBOT_IDS):
        benchmark = benchmarks[benchmark_id]
        workload = benchmark_id.removeprefix("rbot-")
        for case in exporter.iter_cases(config, benchmark):
            flat_case_id = f"{benchmark_id}__{case.case_id}"
            row = manifest_cases.get(flat_case_id)
            if row is not None and row.get("workload") != workload:
                raise LogosMaterializationError(
                    f"{flat_case_id} workload binding changed"
                )
            exported.append(flat_case_id)

    duplicates = sorted(
        case_id for case_id in set(exported) if exported.count(case_id) != 1
    )
    actual = set(exported)
    expected = set(manifest_cases)
    if duplicates or actual != expected or len(exported) != len(expected):
        raise LogosMaterializationError(
            "configured/exported R-Bot cases differ from the frozen 59-case authority: "
            f"duplicates={duplicates[:12]} "
            f"missing={sorted(expected - actual)[:12]} "
            f"unexpected={sorted(actual - expected)[:12]}"
        )
    for case_id, row in sorted(manifest_cases.items()):
        workload = row.get("workload")
        if (
            workload not in FROZEN_RBOT_SCHEMA_SHA256
            or not case_id.startswith(f"rbot-{workload}__")
        ):
            raise LogosMaterializationError(
                f"malformed frozen R-Bot case authority for {case_id}"
            )
        for field, digest_field in (
            ("source", "sourceSha256"),
            ("target", "targetSha256"),
        ):
            bound_manifest_bytes(
                manifest_input_path(row, field), row, digest_field
            )


def bound_rbot_schema_bytes(workload: str) -> bytes:
    expected = FROZEN_RBOT_SCHEMA_SHA256.get(workload)
    if expected is None:
        raise LogosMaterializationError(f"unsupported R-Bot workload {workload!r}")
    path = RBOT_ROOT / workload / "create_tables.sql"
    try:
        value = path.read_bytes()
    except OSError as exc:
        raise LogosMaterializationError(
            f"frozen R-Bot schema is missing: {path}"
        ) from exc
    actual = sha256_bytes(value)
    if actual != expected:
        raise LogosMaterializationError(
            f"R-Bot {workload} schema digest changed from the frozen authority: "
            f"expected {expected}, got {actual}"
        )
    return value


def materialize_rbot_case(
    config: dict[str, Any],
    case: Any,
    output_dir: Path,
    manifest: dict[str, Any],
    manifest_cases: dict[str, dict[str, Any]],
) -> None:
    benchmark = case.benchmark
    flat_case_id = f"{benchmark['id']}__{case.case_id}"
    row = manifest_cases.get(flat_case_id)
    if row is None:
        raise LogosMaterializationError(
            f"{flat_case_id} is outside the frozen 59-case manifest"
        )
    workload = benchmark["id"].removeprefix("rbot-")
    if row.get("workload") != workload:
        raise LogosMaterializationError(f"{flat_case_id} workload binding changed")

    source_path = manifest_input_path(row, "source")
    target_path = manifest_input_path(row, "target")
    schema_path = RBOT_ROOT / workload / "create_tables.sql"
    source_bytes = bound_manifest_bytes(source_path, row, "sourceSha256")
    target_bytes = bound_manifest_bytes(target_path, row, "targetSha256")
    schema_bytes = bound_rbot_schema_bytes(workload)

    case_dir = output_dir / flat_case_id
    case_dir.mkdir(parents=True, exist_ok=True)
    write_bytes(case_dir / "schema.sql", schema_bytes)
    write_bytes(case_dir / "sql1.sql", source_bytes)
    write_bytes(case_dir / "sql2.sql", target_bytes)

    manifest_digest = FROZEN_RBOT_MANIFEST_SHA256
    inputs = {
        "schema": unchanged_input_contract(schema_path, schema_bytes, "schema.sql"),
        "source": unchanged_input_contract(source_path, source_bytes, "sql1.sql"),
        "target": unchanged_input_contract(target_path, target_bytes, "sql2.sql"),
    }
    defaults = config["defaults"]
    metadata = {
        "adapter": benchmark.get("adapter", defaults.get("adapter", "none")),
        "bagSemantics": benchmark.get("bagSemantics", defaults["bagSemantics"]),
        "calciteAuthorityInputs": {
            name: {
                "path": value["outputPath"],
                "sha256": value["outputSha256"],
            }
            for name, value in inputs.items()
        },
        "constraintScope": benchmark.get("constraintScope", "none"),
        "constraints": [],
        "featureTags": case.feature_tags,
        "flatCaseId": flat_case_id,
        "frontendTargetDialectPurpose": benchmark.get(
            "frontendTargetDialectPurpose",
            defaults.get("frontendTargetDialectPurpose"),
        ),
        "integrityContract": {
            "authoritativeForLogos": True,
            "ddlComplete": True,
            "ddlLimitation": None,
            "silentDrops": 0,
            "sources": [{"kind": "parser_facing_ddl", "path": "schema.sql"}],
        },
        "materializationContract": {
            "inputs": inputs,
            "policy": "logos-postgres-calcite-source-preserving-v1",
            "semanticPreservation": {
                "established": True,
                "identifierDelimitersPreserved": True,
                "queryStructurePreserved": True,
                "repairs": [],
            },
            "sourceManifest": "benchmarks/core/rbot/rewrite-pairs.manifest.json",
            "sourceManifestSha256": manifest_digest,
        },
        "nullSemantics": benchmark.get("nullSemantics", defaults["nullSemantics"]),
        "profile": "logos",
        "readDialect": case.read_dialect or benchmark.get("readDialect"),
        "schemaScope": benchmark["schemaScope"],
        "semanticProfile": benchmark.get(
            "semanticProfile", defaults["semanticProfile"]
        ),
        "source": {
            **case.source_metadata,
            "manifestCase": row["case"],
            "manifestProfile": manifest.get("profile"),
        },
        "sourceBenchmark": benchmark["id"],
        "sourceCase": case.case_id,
        "sourceDialect": case.source_dialect or benchmark.get("sourceDialect"),
        "writeDialect": case.write_dialect
        or benchmark.get("writeDialect", defaults.get("writeDialect")),
    }
    write_text(
        case_dir / "metadata.json",
        json.dumps(metadata, indent=2, sort_keys=True) + "\n",
    )


def manifest_input_path(row: dict[str, Any], field: str) -> Path:
    value = row.get(field)
    if not isinstance(value, str) or not value or Path(value).is_absolute():
        raise LogosMaterializationError(f"R-Bot manifest field {field} is invalid")
    relative = Path(value)
    if ".." in relative.parts:
        raise LogosMaterializationError(
            f"R-Bot manifest field {field} escapes its root"
        )
    path = RBOT_ROOT / relative
    if not path.is_file():
        raise LogosMaterializationError(f"R-Bot manifest input is missing: {value}")
    return path


def bound_manifest_bytes(path: Path, row: dict[str, Any], digest_field: str) -> bytes:
    expected = row.get(digest_field)
    value = path.read_bytes()
    actual = sha256_bytes(value)
    if not isinstance(expected, str) or actual != expected:
        raise LogosMaterializationError(
            f"R-Bot manifest digest mismatch for {path}: expected {expected}, got {actual}"
        )
    return value


def unchanged_input_contract(
    path: Path, value: bytes, output_name: str
) -> dict[str, Any]:
    digest = sha256_bytes(value)
    return {
        "inputPath": path.relative_to(ROOT).as_posix(),
        "inputSha256": digest,
        "outputPath": output_name,
        "outputSha256": digest,
        "repairs": [],
        "unchanged": True,
    }


def materialize_legacy_non_rbot_case(
    config: dict[str, Any], case: Any, output_dir: Path, exporter: Any
) -> None:
    benchmark = case.benchmark
    flat_case_id = f"{benchmark['id']}__{case.case_id}"
    case_dir = output_dir / flat_case_id
    case_dir.mkdir(parents=True, exist_ok=True)
    read_dialect = case.read_dialect or benchmark.get("readDialect") or "postgres"
    write_dialect = case.write_dialect or benchmark.get("writeDialect") or "postgres"
    adapter = benchmark.get("adapter", config["defaults"].get("adapter", "none"))
    before_sql, after_sql, date_day_bridge = exporter.patch_tsql_date_day_pair(case)
    before_sql = materialize_frozen_calcite_integer_casts(case, "before", before_sql)
    after_sql = materialize_frozen_calcite_integer_casts(case, "after", after_sql)

    with tempfile.TemporaryDirectory(prefix="logos-legacy-nonrbot-") as tmp:
        tmp_dir = Path(tmp)
        schema_source = write_text(tmp_dir / "schema.source.sql", case.schema_sql)
        sql1_source = write_text(
            tmp_dir / "sql1.source.sql", ensure_sql_terminated(before_sql)
        )
        sql2_source = write_text(
            tmp_dir / "sql2.source.sql", ensure_sql_terminated(after_sql)
        )
        schema_target = tmp_dir / "schema.sql"
        schema_report = tmp_dir / "schema.normalization.json"
        normalize_sql_legacy(
            source=schema_source,
            target=schema_target,
            report=schema_report,
            read=read_dialect,
            write="mysql",
            identify=False,
        )

        query_reports: dict[str, dict[str, Any]] = {}
        if adapter == "sqlglot":
            sql1_target = tmp_dir / "sql1.sql"
            sql2_target = tmp_dir / "sql2.sql"
            before_report = tmp_dir / "sql1.normalization.json"
            after_report = tmp_dir / "sql2.normalization.json"
            normalize_sql_legacy(
                source=sql1_source,
                target=sql1_target,
                report=before_report,
                read=read_dialect,
                write=write_dialect,
                identify=False,
            )
            normalize_sql_legacy(
                source=sql2_source,
                target=sql2_target,
                report=after_report,
                read=read_dialect,
                write=write_dialect,
                identify=False,
            )
            query_reports["before"] = json.loads(before_report.read_text())
            query_reports["after"] = json.loads(after_report.read_text())
        else:
            sql1_target = sql1_source
            sql2_target = sql2_source
            query_reports["before"] = {"skipped": True}
            query_reports["after"] = {"skipped": True}

        write_text(case_dir / "schema.sql", schema_target.read_text())
        write_text(case_dir / "sql1.sql", ensure_one_line(sql1_target.read_text()))
        write_text(case_dir / "sql2.sql", ensure_one_line(sql2_target.read_text()))
        metadata = {
            **build_legacy_non_rbot_metadata(config, case, flat_case_id),
            **(
                {"pairedTsqlDateDayBridge": date_day_bridge}
                if date_day_bridge is not None
                else {}
            ),
            "normalizationForSolverRun": {
                "schema": {
                    "readDialect": read_dialect,
                    "writeDialect": "mysql",
                    "report": json.loads(schema_report.read_text()),
                    "semanticNote": (
                        "DDL-only dialect materialization for SQLSolver's MySQL "
                        "schema parser. SQLGlot maps unbounded VARCHAR to TEXT "
                        "without adding a 255-character bound."
                    ),
                },
                "before": query_reports["before"],
                "after": query_reports["after"],
            },
        }
        write_text(
            case_dir / "metadata.json",
            json.dumps(metadata, indent=2, sort_keys=True) + "\n",
        )


def build_legacy_non_rbot_metadata(
    config: dict[str, Any], case: Any, flat_case_id: str
) -> dict[str, Any]:
    defaults = config["defaults"]
    benchmark = case.benchmark
    raw_constraints = case.constraints
    if raw_constraints is None:
        constraints: list[dict[str, Any]] = []
    elif isinstance(raw_constraints, list):
        constraints = raw_constraints
    else:
        raise LogosMaterializationError(
            f"{flat_case_id} constraints must be a list or null"
        )
    constraint_scope = benchmark.get("constraintScope", "none")
    contract_sources = [{"kind": "parser_facing_ddl", "path": "schema.sql"}]
    if constraint_scope == "pair":
        contract_sources.append(
            {"kind": "pair_metadata", "path": "metadata.json#/constraints"}
        )
    return {
        "sourceBenchmark": benchmark["id"],
        "sourceCase": case.case_id,
        "flatCaseId": flat_case_id,
        "source": case.source_metadata,
        "schemaScope": benchmark["schemaScope"],
        "constraintScope": constraint_scope,
        "constraints": constraints,
        "integrityContract": {
            "authoritativeForLogos": True,
            "sources": contract_sources,
            "silentDrops": 0,
            "sqlsolverDdlComplete": not constraints,
            "sqlsolverDdlLimitation": (
                "SQLSolver reads schema.sql only; pair-level declarations are "
                "retained in adjacent metadata for the authoritative Logos contract."
                if constraints
                else None
            ),
        },
        "adapter": benchmark.get("adapter", defaults.get("adapter", "none")),
        "sourceDialect": case.source_dialect or benchmark.get("sourceDialect"),
        "readDialect": case.read_dialect or benchmark.get("readDialect"),
        "writeDialect": case.write_dialect
        or benchmark.get("writeDialect", defaults.get("writeDialect")),
        "frontendTargetDialectPurpose": benchmark.get(
            "frontendTargetDialectPurpose",
            defaults.get("frontendTargetDialectPurpose"),
        ),
        "semanticProfile": benchmark.get(
            "semanticProfile", defaults["semanticProfile"]
        ),
        "bagSemantics": benchmark.get("bagSemantics", defaults["bagSemantics"]),
        "nullSemantics": benchmark.get("nullSemantics", defaults["nullSemantics"]),
        "featureTags": case.feature_tags,
        "profile": "sqlsolver",
    }


def materialize_frozen_calcite_integer_casts(case: Any, side: str, sql: str) -> str:
    """Replay exact validator-inserted VARCHAR-to-INTEGER source casts.

    This is a shape rule, not a case allowlist.  It activates only for the
    retained Calcite-derived benchmark and only when generated Calcite
    authority identifies an implicit one-operand VARCHAR-to-INTEGER cast at an
    exact source span.  The authority metadata, embedded SQL, span text, and
    replacement must all agree; malformed or conflicting evidence fails closed.

    The historical non-R-Bot bytes predate later aggregate-result coercion
    classes, so this frozen renderer intentionally recognizes no other cast.
    """

    benchmark_id = case.benchmark["id"]
    if benchmark_id != "verieql-calcite":
        return sql
    if side not in {"before", "after"}:
        raise LogosMaterializationError(f"invalid Calcite side {side!r}")
    authority_dir = CALCITE_AUTHORITY_ROOT / benchmark_id / case.case_id
    metadata_path = authority_dir / "metadata.json"
    ir_path = authority_dir / f"{side}.calcite-ir.json"
    try:
        metadata = json.loads(metadata_path.read_text(encoding="utf-8"))
        ir = json.loads(ir_path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        raise LogosMaterializationError(
            f"missing or invalid frozen Calcite authority for {benchmark_id}/{case.case_id}"
        ) from exc
    if (
        metadata.get("sourceBenchmark") != benchmark_id
        or metadata.get("sourceCase") != case.case_id
        or metadata.get("source") != case.source_metadata
    ):
        raise LogosMaterializationError(
            f"stale Calcite authority metadata for {benchmark_id}/{case.case_id}"
        )
    queries = ir.get("queries")
    if (
        not isinstance(queries, list)
        or len(queries) != 1
        or not isinstance(queries[0], dict)
        or program_text(queries[0].get("sql")) != program_text(sql)
    ):
        raise LogosMaterializationError(
            f"Calcite authority SQL drift for {benchmark_id}/{case.case_id} {side}"
        )

    rewrites: dict[tuple[int, int], str] = {}
    for node in walk_json(queries[0].get("rel")):
        if node.get("kind") != "CAST" or node.get("sourceKind") == "CAST":
            continue
        operands = node.get("operands")
        if (
            not isinstance(operands, list)
            or len(operands) != 1
            or not isinstance(operands[0], dict)
            or str(operands[0].get("type", "")).upper() != "VARCHAR"
            or str(node.get("type", "")).upper() != "INTEGER"
        ):
            continue
        node_id = node.get("sourceNodeId")
        source_text = node.get("sourceText")
        if not isinstance(node_id, str) or not isinstance(source_text, str):
            raise LogosMaterializationError(
                "implicit Calcite integer cast lacks source identity"
            )
        start, end = source_span(sql, node_id)
        if sql[start:end] != source_text:
            raise LogosMaterializationError(
                f"Calcite source span {node_id} does not match {source_text!r}"
            )
        replacement = f"CAST({source_text} AS INTEGER)"
        prior = rewrites.get((start, end))
        if prior is not None and prior != replacement:
            raise LogosMaterializationError(f"conflicting Calcite casts at {node_id}")
        rewrites[(start, end)] = replacement

    ordered = sorted(rewrites.items())
    for ((left_start, left_end), _), ((right_start, _), _) in zip(ordered, ordered[1:]):
        if right_start < left_end:
            raise LogosMaterializationError(
                f"overlapping Calcite cast spans at {left_start} and {right_start}"
            )
    result = sql
    for (start, end), replacement in reversed(ordered):
        result = result[:start] + replacement + result[end:]
    return result


def walk_json(value: Any):
    if isinstance(value, dict):
        yield value
        for child in value.values():
            yield from walk_json(child)
    elif isinstance(value, list):
        for child in value:
            yield from walk_json(child)


def program_text(value: Any) -> str | None:
    if not isinstance(value, str):
        return None
    text = value.strip(" \t\r\n\f")
    if text.endswith(";"):
        text = text[:-1].rstrip(" \t\r\n\f")
    return text


def source_span(sql: str, node_id: str) -> tuple[int, int]:
    match = SOURCE_NODE_ID.fullmatch(node_id)
    if match is None:
        raise LogosMaterializationError(f"invalid Calcite source node ID {node_id!r}")
    start_line, start_column, end_line, end_column = map(int, match.groups())
    if min(start_line, start_column, end_line, end_column) < 1:
        raise LogosMaterializationError(f"invalid Calcite source node ID {node_id!r}")
    lines = sql.splitlines(keepends=True)
    if start_line > len(lines) or end_line > len(lines):
        raise LogosMaterializationError(f"Calcite source node escapes SQL: {node_id}")

    def offset(line: int, column: int) -> int:
        body = lines[line - 1]
        content_length = len(body.rstrip("\r\n"))
        if column - 1 > content_length:
            raise LogosMaterializationError(
                f"Calcite source column escapes SQL: {node_id}"
            )
        return sum(len(item) for item in lines[: line - 1]) + column - 1

    start = offset(start_line, start_column)
    end = offset(end_line, end_column) + 1
    if start >= end or end > len(sql):
        raise LogosMaterializationError(f"invalid Calcite source span: {node_id}")
    return start, end


def materialize_wetune_cases(
    *,
    config: dict[str, Any],
    output_dir: Path,
    case_patterns: list[re.Pattern[str]],
    limit: int | None,
) -> tuple[int, int]:
    benchmark = next(item for item in config["benchmarks"] if item["id"] == WETUNE_ID)
    spec = benchmark["caseSource"]
    issues_path = resolve_path(benchmark["source"])
    columns = spec["columns"]
    output_dir.mkdir(parents=True, exist_ok=True)
    materialized = 0
    failed = 0

    # The copied renderer calls this module global.  Rebinding it keeps the
    # renderer independent while selecting the exact frozen SQLGlot contract.
    logos_legacy_wetune.normalize_query = normalize_wetune_query_legacy

    with issues_path.open(newline="") as handle:
        for row in csv.DictReader(handle, delimiter="\t", fieldnames=columns):
            case_id = str(row["id"])
            if case_patterns and not any(
                pattern.search(case_id) for pattern in case_patterns
            ):
                continue
            if limit is not None and materialized >= limit:
                break
            app_name = str(row["app_name"])
            schema_path = resolve_path(spec["schema"].format(**row))
            try:
                logos_legacy_wetune.materialize_case(
                    root=ROOT,
                    case_dir=output_dir / case_id,
                    case_id=case_id,
                    app_name=app_name,
                    rewrite_type=str(row["rewrite_type"]),
                    commit_url=str(row["commit_url"]),
                    schema_path=schema_path,
                    before_sql=str(row["before_sql"]),
                    after_sql=str(row["after_sql"]),
                )
                materialized += 1
                print(f"materialized wetune-issues/{case_id}", file=sys.stderr)
            except Exception as exc:
                failed += 1
                print(f"failed wetune-issues/{case_id}: {exc}", file=sys.stderr)
    return materialized, failed


