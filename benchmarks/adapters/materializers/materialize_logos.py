#!/usr/bin/env python3
"""Materialize the SQL, integrity, and Calcite-authority inputs consumed by Logos.

This frontend is deliberately independent of every external solver frontend.
For the frozen R-Bot corpus it copies the manifest-bound PostgreSQL/Calcite SQL
bytes without identifier delimiter elision, serialization, or solver admission.

The pre-existing non-R-Bot Logos campaign is a byte regression boundary.  Its
historical generated representation is reproduced from core sources by a
frozen compatibility renderer.  Historical serialized field values mentioning
SQLSolver are retained only because ``metadata.json`` itself is part of the
1,320-file byte baseline; they do not select or invoke an SQLSolver policy.
"""

from __future__ import annotations

